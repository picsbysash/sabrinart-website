const SITE = 'SabrinArt Collection';
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

export default async (request, context) => {
  const res = await context.next();
  if (!(res.headers.get('content-type') || '').includes('text/html')) return res;
  const url = new URL(request.url);
  const parts = url.pathname.replace(/\/+$/, '').split('/');
  const route = parts[1] || 'home';
  const sub = parts[2];
  let title, desc, image = 'assets/artworks/wow.jpg';
  const w = (route === 'gallery' || route === 'artwork') && sub ? DATA.works[sub] : null;
  if (w) {
    title = w.t + ' · ' + w.m + ' · ' + SITE; desc = w.d; image = w.i;
  } else {
    const p = DATA.pages[route] || DATA.pages.home;
    title = p[0]; desc = p[1];
  }
  const origin = url.origin;
  const tags = [
    '<meta name="description" content="' + esc(desc) + '" data-sa>',
    '<link rel="canonical" href="' + esc(origin + url.pathname) + '" data-sa>',
    '<meta property="og:site_name" content="' + SITE + '" data-sa>',
    '<meta property="og:type" content="website" data-sa>',
    '<meta property="og:title" content="' + esc(title) + '" data-sa>',
    '<meta property="og:description" content="' + esc(desc) + '" data-sa>',
    '<meta property="og:url" content="' + esc(origin + url.pathname) + '" data-sa>',
    '<meta property="og:image" content="' + esc(origin + '/' + image) + '" data-sa>',
    '<meta name="twitter:card" content="summary_large_image" data-sa>'
  ].join('\n    ');
  let html = await res.text();
  html = html.replace(/<title>[\s\S]*?<\/title>/, '<title>' + esc(title) + '</title>')
    .replace(/<(meta|link)[^>]*data-sa[^>]*>\s*/g, '')
    .replace('</head>', '    ' + tags + '\n</head>');
  const headers = new Headers(res.headers);
  headers.delete('content-length');
  return new Response(html, { status: res.status, headers });
};

